import 'package:postgres/postgres.dart';
import '../core/db_connection.dart';
import '../models/student.dart';

class StudentRepository {
  Connection get db => DbConnection.connection;

  // Get all students with their program information
  Future<List<Student>> getAll() async {
    final result = await db.execute(
      Sql.named('''
        SELECT
          s.student_id,
          s.student_name,
          s.program_id,
          p.program_code,
          p.program_name
        FROM students s
        LEFT JOIN program p
          ON p.program_id = s.program_id
        ORDER BY s.student_name
      '''),
    );

    return result.map((row) => Student.fromMap(row.toColumnMap())).toList();
  }

  // Add student - student_id is automatically generated by PostgreSQL
  Future<void> add(Student student) async {
    final data = student.toMap();

    await db.execute(
      Sql.named('''
        INSERT INTO students (
          student_name,
          program_id
        )
        VALUES (
          @student_name,
          @program_id
        )
      '''),
      parameters: {
        'student_name': data['student_name'],
        'program_id': data['program_id'],
      },
    );
  }

  // Update existing student
  Future<void> update(Student student) async {
    final data = student.toMap();

    await db.execute(
      Sql.named('''
        UPDATE students
        SET
          student_name = @student_name,
          program_id = @program_id
        WHERE student_id = @id
      '''),
      parameters: {
        'student_name': data['student_name'],
        'program_id': data['program_id'],
        'id': student.id,
      },
    );
  }

  // Delete student and related records
  Future<void> delete(int id) async {
    // Check legacy grade records first
    final legacy = await db.execute(
      Sql.named('''
        SELECT COUNT(*)
        FROM grades_legacy
        WHERE student_id = @id
      '''),
      parameters: {'id': id},
    );

    if ((legacy.first[0] as int) > 0) {
      throw Exception('This student has records in grades_legacy.');
    }

    // Delete related records using a transaction
    await db.runTx((tx) async {
      await tx.execute(
        Sql.named('''
          DELETE FROM grades
          WHERE enrollment_id IN (
            SELECT enrollment_id
            FROM enrollments
            WHERE student_id = @id
          )
        '''),
        parameters: {'id': id},
      );

      await tx.execute(
        Sql.named('''
          DELETE FROM enrollments
          WHERE student_id = @id
        '''),
        parameters: {'id': id},
      );

      await tx.execute(
        Sql.named('''
          DELETE FROM students
          WHERE student_id = @id
        '''),
        parameters: {'id': id},
      );
    });
  }
}
